if os.environ.get('CLOUDINARY_URL'):
    INSTALLED_APPS += ['cloudinary_storage', 'cloudinary']
    STORAGES["default"] = {"BACKEND": "cloudinary_storage.storage.MediaCloudinaryStorage"}

elif os.environ.get('AWS_STORAGE_BUCKET_NAME'):
    # Works for both AWS S3 and DigitalOcean Spaces (S3-compatible API) —
    # for DO Spaces, also set AWS_S3_ENDPOINT_URL to your Spaces endpoint.
    INSTALLED_APPS += ['storages']
    STORAGES["default"] = {"BACKEND": "storages.backends.s3.S3Storage"}
    AWS_STORAGE_BUCKET_NAME = os.environ.get('AWS_STORAGE_BUCKET_NAME')
    AWS_ACCESS_KEY_ID = os.environ.get('AWS_ACCESS_KEY_ID')
    AWS_SECRET_ACCESS_KEY = os.environ.get('AWS_SECRET_ACCESS_KEY')
    AWS_S3_REGION_NAME = os.environ.get('AWS_S3_REGION_NAME', 'us-east-1')
    AWS_S3_ENDPOINT_URL = os.environ.get('AWS_S3_ENDPOINT_URL')  # only needed for DO Spaces
    AWS_S3_FILE_OVERWRITE = False
    AWS_DEFAULT_ACL = None

