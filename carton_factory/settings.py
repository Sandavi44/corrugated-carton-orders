# --- File storage: local -> Cloudinary -> S3/DO Spaces, switched by env vars only ---
#
# Free/dev mode (default): files saved to the local /media folder. Fine for
# testing, but on most hosts this does NOT survive a redeploy — don't rely
# on it once real pattern images matter.
#
# Set CLOUDINARY_URL to switch to Cloudinary (recommended starting point —
# generous free tier, simplest setup). Get this value from your Cloudinary
# dashboard after creating a free account: https://cloudinary.com
#
# Later, to move to S3 or DigitalOcean Spaces instead, set AWS_* variables
# below and leave CLOUDINARY_URL unset — no code changes needed either way,
# just environment variables on whichever host you deploy to.

STORAGES = {
    "default": {"BACKEND": "django.core.files.storage.FileSystemStorage"},
    "staticfiles": {
        "BACKEND": (
            "whitenoise.storage.CompressedManifestStaticFilesStorage"
            if not DEBUG else
            "django.contrib.staticfiles.storage.StaticFilesStorage"
        )
    },
}

MEDIA_URL = 'media/'
